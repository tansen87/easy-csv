// Generates `src/utils/pinyinInitials.ts`.
//
// The command palette matches Chinese labels by pinyin initials (`dk` → 打开文件).
// Doing that at runtime would mean shipping a pinyin dependency (or an async
// plugin call), so the table is precomputed here instead: every distinct CJK
// character used by the UI is fed to the bundled `pinyin` plugin CLI
// (`plugins/pinyin-cli`, `-s plain` prints just the initial), and the result is
// written as two parallel strings that the app turns into a Map once.
//
// Re-run after changing Chinese labels or command descriptions:
//   node scripts/gen-pinyin-initials.mjs
// Requires `plugins/pinyin-cli/target/release/pinyin` (cargo build --release).
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const SOURCES = [
  ...readdirSync(join(ROOT, "src/i18n/translations/zh"))
    .filter((f) => f.endsWith(".ts"))
    .map((f) => join(ROOT, "src/i18n/translations/zh", f)),
  ...readdirSync(join(ROOT, "src/data/commands"))
    .filter((f) => f.endsWith(".ts"))
    .map((f) => join(ROOT, "src/data/commands", f)),
];
const OUT = join(ROOT, "src/utils/pinyinInitials.ts");
const EXE = join(
  ROOT,
  "plugins/pinyin-cli/target/release/pinyin" + (process.platform === "win32" ? ".exe" : ""),
);

/** Han characters only: the table is keyed by one char, so no ranges/words. */
const HAN = /\p{Script=Han}/u;

const chars = new Set();
for (const file of SOURCES) {
  for (const ch of readFileSync(file, "utf8")) {
    if (HAN.test(ch)) chars.add(ch);
  }
}
const sorted = [...chars].sort();
if (!sorted.length) throw new Error("no Han characters found in sources");

if (!existsSync(EXE)) {
  throw new Error(
    `pinyin CLI not found at ${EXE}\nBuild it first: cargo build --release (in plugins/pinyin-cli)`,
  );
}

// One character per row: `-s plain` then prints exactly that character's initial.
const dir = mkdtempSync(join(tmpdir(), "easycsv-pinyin-"));
const csv = join(dir, "chars.csv");
const out = join(dir, "out.csv");
try {
  writeFileSync(csv, "ch\n" + sorted.join("\n") + "\n", "utf8");
  execFileSync(EXE, ["-c", "ch", "-s", "plain", "-o", out, csv], { stdio: "inherit" });
  const rows = readFileSync(out, "utf8").split(/\r?\n/).filter(Boolean).slice(1);
  if (rows.length !== sorted.length) {
    throw new Error(`row count mismatch: ${rows.length} rows for ${sorted.length} chars`);
  }
  const initials = rows.map((r) => r.trim().toLowerCase());
  const bad = initials.findIndex((v) => !/^[a-z]$/.test(v));
  if (bad >= 0) throw new Error(`unexpected initial "${initials[bad]}" for "${sorted[bad]}"`);

  const body = `// AUTO-GENERATED by scripts/gen-pinyin-initials.mjs — do not edit by hand.
//
// ${sorted.length} 个汉字的拼音首字母,数据源是 zh i18n 与 xan 命令描述。
// 命令面板用它把 \`dk\` 匹配到「打开文件」。表里没有的字直接跳过(只会少匹配,
// 不会错匹配);标签改动后重跑脚本。
const CHARS = ${JSON.stringify(sorted.join(""))};
const INITIALS = ${JSON.stringify(initials.join(""))};

let table: Map<string, string> | null = null;

function buildTable(): Map<string, string> {
  const map = new Map<string, string>();
  const chars = Array.from(CHARS);
  const initials = Array.from(INITIALS);
  for (let i = 0; i < chars.length; i += 1) map.set(chars[i], initials[i]);
  return map;
}

/**
 * Pinyin initials of the Han characters in \`text\` (lowercase, latin and
 * punctuation dropped). Returns "" when nothing is mappable, which callers
 * treat as "no match" rather than an empty-string match.
 */
export function pinyinInitials(text: string): string {
  table ??= buildTable();
  let out = "";
  for (const ch of text) {
    const initial = table.get(ch);
    if (initial) out += initial;
  }
  return out;
}
`;
  writeFileSync(OUT, body, "utf8");
  console.log(`wrote ${OUT} · ${sorted.length} chars`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
